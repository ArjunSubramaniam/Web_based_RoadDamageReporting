function isoDaysAgo(days, hours = 10) {
  const d = new Date()
  d.setDate(d.getDate() - days)
  d.setHours(hours, (days * 7) % 60, 0, 0)
  return d.toISOString()
}

function history(events) {
  return events.map((event) => ({
    status: event.status,
    at: event.at,
    by: event.by,
    role: event.role,
    note: event.note || '',
  }))
}

function normalizeReport(report) {
  const address = (report.address || '').replace('', '')
  const parts = address.split(',').map((part) => part.trim()).filter(Boolean)
  return {
    ...report,
    category: CATEGORY_ALIASES[report.category] || report.category,
    address,
    roadName: report.roadName || parts[0] || '',
    locality: report.locality || parts[1] || '',
    city: report.city || parts[2] || parts[1] || '',
    postalCode: report.postalCode || '',
  }
}

